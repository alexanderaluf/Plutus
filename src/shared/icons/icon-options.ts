export type IconOption = { name: string; label: string };
export type IconGroup = { title: string; icons: IconOption[] };

function iconLabel(name: string) {
  return name
    .replace(/^material:/, "")
    .split(/[_-]+/)
    .map((word) => (word ? `${word[0].toUpperCase()}${word.slice(1)}` : word))
    .join(" ");
}

function materialIcons(names: string[]): IconOption[] {
  return names.map((name) => ({
    name: `material:${name}`,
    label: iconLabel(name),
  }));
}

function materialGroup(title: string, names: string[]): IconGroup {
  return { title, icons: materialIcons(names) };
}

